@app.route(
    "/atendimentos/chunk",
    methods=["POST"]
)
def receber_chunk():

    usuario_id = usuario_logado()

    if not usuario_id:

        return jsonify({
            "erro": "Nao autenticado"
        }), 401

    if "audio" not in request.files:

        return jsonify({
            "erro": "Sem audio"
        }), 400

    atendimento_id = request.form.get("atendimento_id")
    ordem = request.form.get("ordem")

    if not atendimento_id or ordem is None:

        return jsonify({
            "erro": "Atendimento ou ordem ausente"
        }), 400

    arquivo = request.files["audio"]
    texto = transcrever_chunk(arquivo)

    with conectar_banco() as conn:

        with conn.cursor() as cursor:

            cursor.execute(
                """
                INSERT INTO transcricoes_chunks (
                    atendimento_id,
                    usuario_id,
                    ordem,
                    texto
                )
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (atendimento_id, ordem)
                DO UPDATE SET texto = EXCLUDED.texto
                """,
                (
                    atendimento_id,
                    usuario_id,
                    int(ordem),
                    texto
                )
            )

            cursor.execute(
                """
                UPDATE atendimentos
                SET status = 'transcrevendo'
                WHERE id = %s
                AND usuario_id = %s
                """,
                (
                    atendimento_id,
                    usuario_id
                )
            )

    return jsonify({
        "status": "chunk_transcrito",
        "texto": texto
    })


@app.route(
    "/atendimentos/finalizar",
    methods=["POST"]
)
def finalizar_atendimento():

    usuario_id = usuario_logado()

    if not usuario_id:

        return jsonify({
            "erro": "Nao autenticado"
        }), 401

    dados = request.get_json(silent=True) or {}

    atendimento_id = dados.get("atendimento_id")
    duracao_segundos = dados.get("duracao_segundos")

    if not atendimento_id:

        return jsonify({
            "erro": "Atendimento ausente"
        }), 400

    with conectar_banco() as conn:

        with conn.cursor() as cursor:

            cursor.execute(
                """
                SELECT texto
                FROM transcricoes_chunks
                WHERE atendimento_id = %s
                AND usuario_id = %s
                ORDER BY ordem
                """,
                (
                    atendimento_id,
                    usuario_id
                )
            )

            textos = [
                row[0]
                for row in cursor.fetchall()
                if row[0]
            ]

    transcricao = limpar_texto(
        " ".join(textos)
    )

    if transcricao:

        resultado = analisar_com_ia(
            transcricao
        )

    else:

        resultado = (
            "Nao foi possivel gerar resumo: "
            "nenhuma transcricao foi capturada."
        )

    with conectar_banco() as conn:

        with conn.cursor() as cursor:

            cursor.execute(
                """
                UPDATE atendimentos
                SET
                    conteudo = %s,
                    transcricao_completa = %s,
                    status = 'finalizado',
                    fim_em = NOW(),
                    duracao_segundos = %s
                WHERE id = %s
                AND usuario_id = %s
                """,
                (
                    resultado,
                    transcricao,
                    duracao_segundos,
                    atendimento_id,
                    usuario_id
                )
            )

    return jsonify({
        "status": "finalizado",
        "resultado": resultado
    })


