@app.route(
    "/transcrever",
    methods=["POST"]
)

def transcrever():

    if "usuario_id" not in session:

        return jsonify({
            "erro": "Nao autenticado"
        })

    if "audio" not in request.files:

        return jsonify({
            "erro": "Sem audio"
        })

    arquivo = request.files["audio"]

    nome_arquivo = (
        str(uuid.uuid4()) +
        ".webm"
    )

    caminho_audio = os.path.join(

        UPLOAD_FOLDER,
        nome_arquivo
    )

    arquivo.save(
        caminho_audio
    )

    processando.append(
        nome_arquivo
    )

    thread = threading.Thread(

        target=processar_em_background,

        args=(

            caminho_audio,
            nome_arquivo,
            session["usuario_id"]
        )
    )

    thread.start()

    return jsonify({

        "status": "processando"

    })

