def limpar_texto(texto):

    texto = re.sub(
        r"\s+",
        " ",
        texto or ""
    )

    return texto.strip()


def usuario_logado():

    return session.get("usuario_id")


def transcrever_chunk(arquivo):

    nome = arquivo.filename or "chunk.webm"
    mime = arquivo.mimetype or "audio/webm"

    resposta = client.audio.transcriptions.create(
        model=TRANSCRIBE_MODEL,
        file=(
            nome,
            arquivo.stream,
            mime
        ),
        language="pt",
        prompt=(
            "Atendimento de suporte ERP em portugues do Brasil. "
            "Priorize termos de ERP, fiscal, nota fiscal, caixa, venda, "
            "cadastro, produto, cliente, financeiro, estoque, PDV, NFC-e, "
            "NF-e, SAT, boleto, XML e Zendesk."
        )
    )

    return limpar_texto(
        getattr(resposta, "text", "")
    )


def analisar_com_ia(transcricao):

    prompt = f"""
Voce e um analista de suporte ERP.

Gere uma documentacao curta, direta e pronta para colar no Zendesk.

Regras:
- Nao invente dados.
- Se nao encontrar uma informacao, escreva "Nao informado".
- Mantenha linguagem profissional.
- Extraia tags curtas no final.

Formato:
Empresa:
Cliente:
Telefone:
Email:
Problema:
Resumo do atendimento:
Acao realizada/orientacao:
Tags:

Transcricao:
{transcricao}
"""

    resposta = client.chat.completions.create(
        model=SUMMARY_MODEL,
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ]
    )

    return resposta.choices[0].message.content


