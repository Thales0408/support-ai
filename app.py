def analisar_com_ia(transcricao):

    prompt = f"""

Você é um analista ERP.

Extraia:

- Empresa
- Cliente
- Telefone
- Email
- Problema
- Resumo curto
- Tags

Máximo 3 linhas.

LIGAÇÃO:
{transcricao}

"""

    resposta = client.chat.completions.create(

        model="gpt-4.1-mini",

        messages=[

            {
                "role": "user",
                "content": prompt
            }

        ]

    )

    return resposta.choices[0].message.content

