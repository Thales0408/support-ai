def conectar_banco():

    db_password = DB_PASSWORD

    if (
        not db_password
        and DATABASE_URL
        and "postgres:@" in DATABASE_URL
        and "@db." in DATABASE_URL
    ):

        db_password = DATABASE_URL.split(
            "postgres:@",
            1
        )[1].split(
            "@db.",
            1
        )[0]

    if db_password:

        return psycopg2.connect(
            host=DB_HOST,
            port=DB_PORT,
            dbname=DB_NAME,
            user=DB_USER,
            password=db_password,
            sslmode="require"
        )

    if not DATABASE_URL:

        raise RuntimeError(
            "DATABASE_URL ou DB_PASSWORD nao configurada"
        )

    return psycopg2.connect(
        DATABASE_URL
    )


