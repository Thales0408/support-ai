@app.route(
    "/login",
    methods=["GET", "POST"]
)
def login():

    if request.method == "POST":

        usuario = request.form["usuario"]
        senha = request.form["senha"]

        with conectar_banco() as conn:

            with conn.cursor() as cursor:

                cursor.execute(
                    """
                    SELECT id
                    FROM usuarios
                    WHERE usuario = %s
                    AND senha = %s
                    """,
                    (
                        usuario,
                        senha
                    )
                )

                user = cursor.fetchone()

        if user:

            session["usuario_id"] = user[0]

            return redirect("/")

    return render_template(
        "login.html"
    )


