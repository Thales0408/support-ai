@app.route("/resultados")
def resultados():

    usuario_id = usuario_logado()

    if not usuario_id:

        return jsonify({
            "resultados": [],
            "processando": []
        })

    with conectar_banco() as conn:

        with conn.cursor() as cursor:

            cursor.execute(
                """
                SELECT
                    id,
                    arquivo,
                    conteudo,
                    data,
                    status
                FROM atendimentos
                WHERE usuario_id = %s
                ORDER BY id DESC
                LIMIT 100
                """,
                (
                    usuario_id,
                )
            )

            rows = cursor.fetchall()

    itens = []
    processando = []

    for row in rows:

        item = {
            "id": row[0],
            "arquivo": row[1],
            "conteudo": row[2],
            "data": row[3],
            "status": row[4]
        }

        itens.append(item)

        if row[4] != "finalizado":

            processando.append(str(row[0]))

    return jsonify({
        "resultados": itens,
        "processando": processando
    })


